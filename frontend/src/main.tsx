import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { BrowserRouter } from 'react-router'
/* ODS telemetry settings, read once before any ODS component mounts. The file
   is generated by the UI kit's postinstall; production builds send nothing. */
import '../telemetry.config.js'
/* ODS (issue #135): fonts, foundation tokens, the default colour schemes and the
   component styles - before index.css, so the panel's own rules come last. */
import '@telekom-ods/design-tokens/typography.css'
import '@telekom-ods/design-tokens/core.css'
import '@telekom-ods/design-tokens/schemes/default.css'
import '@telekom-ods/react-ui-kit/style.css'
import './index.css'
import App from './App.tsx'
import { AuthGate } from './shared/auth/AuthGate.tsx'
import { I18nProvider } from './shared/i18n'
import { ThemeProvider } from './shared/theme'

const queryClient = new QueryClient({
  defaultOptions: { queries: { staleTime: 15_000, retry: 1 } },
})

createRoot(document.getElementById('root')!).render(
  <StrictMode>
      <QueryClientProvider client={queryClient}>
          <BrowserRouter>
              <I18nProvider>
                  <ThemeProvider>
                      <AuthGate>
                          <App />
                      </AuthGate>
                  </ThemeProvider>
              </I18nProvider>
          </BrowserRouter>
      </QueryClientProvider>
  </StrictMode>,
)
